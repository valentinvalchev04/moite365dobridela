window.IDEAS = (() => {
  const cats = window.IDEAS_CATS.map(c => ({ c, i: 0 })), out = [];
  while (out.length < 365) {
    let added = false;
    for (const x of cats) { if (x.i < x.c.items.length && out.length < 365) { const t = x.c.items[x.i++]; out.push({ cat: x.c.id, name: x.c.name, ic: x.c.ic, book: t.startsWith('*'), text: t.replace(/^\*/, '') }); added = true; } }
    if (!added) break;
  }
  return out;
})();
